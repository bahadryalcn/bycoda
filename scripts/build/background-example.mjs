import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../../", import.meta.url));
const data = join(root, "src/features/settings/data/backgrounds");
const output = await build({
  entryPoints: [join(data, "three-runtime.js")],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  globalName: "THREE",
  target: "es2020",
  legalComments: "inline",
});
const license = await readFile(join(root, "node_modules/three/LICENSE"), "utf8");
// Portable scenes retain the complete license even without the application repository.
// GLSL template strings retain upstream padding; omit that padding in the portable bundle.
const runtime = `/* ${license} */\n${output.outputFiles[0].text.replace(/[\t ]+\n/g, "\n")}`;
await mkdir(join(root, "vendor/three"), { recursive: true });
await writeFile(join(root, "vendor/three/LICENSE"), license);
await writeFile(
  join(data, "three-runtime.generated.ts"),
  `// Generated by scripts/build/background-example.mjs. Three.js r180, MIT; see vendor/three/LICENSE.\nexport const THREE_RUNTIME = ${JSON.stringify(runtime)};\n`,
);
const source = await readFile(join(data, "mountain-lake.js"), "utf8");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Mountain lake at dusk</title><!-- Three.js r180, MIT. https://threejs.org/ . License: ${license.replaceAll("--", "- -")} --><script>${runtime.replaceAll("</script", "<\\/script")}</script></head><body><!--bycoda:scene-source--><style>html,body,#scene{margin:0;width:100%;height:100%;overflow:hidden;background:#283d50}canvas{display:block;width:100%;height:100%}#scene[data-failed]{display:grid;place-items:center;color:#eee;font:14px system-ui}</style><div id="scene"></div><script>${source}</script></body></html>`;
await writeFile(join(data, "mountain-lake.html"), html);
console.log(
  `Offline Three.js runtime ${Buffer.byteLength(runtime)} bytes; complete landscape ${Buffer.byteLength(html)} bytes.`,
);
