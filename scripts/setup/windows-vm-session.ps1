#Requires -Version 5.1
<#
Prepare only the dedicated build guest's nonadministrator interactive identity.
Account passwords are generated by the OS RNG and held in an LSA secret, never
returned to the controller, arguments or a plaintext autologon registry value.
#>
[CmdletBinding()]
param(
    [ValidateSet('Plan', 'Status', 'CreateAccount', 'EnableRunnerSession')][string]$Mode = 'Plan',
    [string]$ExpectedVmUuid
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$accountName = 'bycoda-runner'
$bootstrapRoot = 'C:\ProgramData\BycodaCI-GuestBootstrap'
$markerPath = "$bootstrapRoot\session-identity.json"
$controlScript = 'C:\bycoda-actions\control\windows-runner.ps1'
$taskName = 'BycodaCIInteractiveRunner'

function Assert-RegularPath([string]$Path) {
    if ($Path -notmatch '^[a-zA-Z]:\\' -or $Path.Substring(2).Contains(':')) { throw 'Guest session paths must be absolute local paths without streams' }
    $cursor = [IO.Path]::GetFullPath($Path)
    while ($cursor) {
        if ((Test-Path -LiteralPath $cursor) -and ((Get-Item -LiteralPath $cursor -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'Guest session paths cannot traverse a reparse point' }
        $next = Split-Path -Parent $cursor
        if ($next -eq $cursor) { break }
        $cursor = $next
    }
}

function Get-EffectiveSessionRights($Rule) {
    if ($Rule.PropagationFlags -band [Security.AccessControl.PropagationFlags]::InheritOnly) { return [long]0 }
    [long]$raw = $Rule.FileSystemRights
    if ($raw -lt 0) { $raw += 4294967296 }
    [long]$mapped = $raw -band 0x0fffffff
    if ($raw -band 0x80000000L) { $mapped = $mapped -bor 0x120089 }
    if ($raw -band 0x40000000L) { $mapped = $mapped -bor 0x120116 }
    if ($raw -band 0x20000000L) { $mapped = $mapped -bor 0x1200a0 }
    if ($raw -band 0x10000000L) { $mapped = $mapped -bor 0x1f01ff }
    return $mapped
}

function Assert-AdminProtected([string]$Path) {
    Assert-RegularPath $Path
    if (-not (Test-Path -LiteralPath $Path)) { throw 'Protected guest prerequisite is missing' }
    $initial = [IO.Path]::GetFullPath($Path)
    $cursor = $initial
    while ($cursor) {
        $acl = Get-Acl -LiteralPath $cursor
        $owner = $acl.GetOwner([Security.Principal.SecurityIdentifier]).Value
        $trusted = @('S-1-5-18', 'S-1-5-32-544', 'S-1-5-80-956008885-3418522649-1831038044-1853292631-2271478464')
        if ($owner -notin $trusted) { throw 'Guest prerequisite owner is not administrator/SYSTEM' }
        $rights = [Security.AccessControl.FileSystemRights]::Delete -bor [Security.AccessControl.FileSystemRights]::DeleteSubdirectoriesAndFiles -bor [Security.AccessControl.FileSystemRights]::ChangePermissions -bor [Security.AccessControl.FileSystemRights]::TakeOwnership
        if ($cursor -eq $initial) { $rights = $rights -bor [Security.AccessControl.FileSystemRights]::Write -bor [Security.AccessControl.FileSystemRights]::Delete }
        foreach ($ace in $acl.GetAccessRules($true, $true, [Security.Principal.SecurityIdentifier])) {
            if ($ace.AccessControlType -eq 'Allow' -and ((Get-EffectiveSessionRights $ace) -band $rights) -and $ace.IdentityReference.Value -notin $trusted) { throw 'Guest prerequisite is writable or replaceable by an untrusted identity' }
        }
        $next = Split-Path -Parent $cursor
        if ($next -eq $cursor) { break }
        $cursor = $next
    }
}

function Set-AdminOnly([string]$Path) {
    $item = Get-Item -LiteralPath $Path -Force
    $acl = if ($item.PSIsContainer) { [Security.AccessControl.DirectorySecurity]::new() } else { [Security.AccessControl.FileSecurity]::new() }
    $acl.SetOwner([Security.Principal.SecurityIdentifier]::new('S-1-5-32-544'))
    $acl.SetAccessRuleProtection($true, $false)
    $inherit = if ($item.PSIsContainer) { [Security.AccessControl.InheritanceFlags]'ContainerInherit,ObjectInherit' } else { [Security.AccessControl.InheritanceFlags]::None }
    foreach ($sid in @('S-1-5-18', 'S-1-5-32-544')) {
        $rule = [Security.AccessControl.FileSystemAccessRule]::new([Security.Principal.SecurityIdentifier]::new($sid), [Security.AccessControl.FileSystemRights]::FullControl, $inherit, [Security.AccessControl.PropagationFlags]::None, [Security.AccessControl.AccessControlType]::Allow)
        $acl.AddAccessRule($rule)
    }
    Set-Acl -LiteralPath $Path -AclObject $acl
}

function Assert-OwnedMarker {
    Assert-AdminProtected $markerPath
    if (-not (Test-Path -LiteralPath $markerPath)) { throw 'Existing guest account has no matching setup ownership record' }
    if ((Get-Item -LiteralPath $markerPath).Length -gt 16384) { throw 'Guest ownership record exceeds size bound' }
    $marker = Get-Content -LiteralPath $markerPath -Raw | ConvertFrom-Json
    if ($marker.kind -ne 'bycoda-runner-session-v1' -or $marker.vmUuid -ne $actualUuid -or $marker.account -ne $accountName) { throw 'Guest account ownership does not match this VM' }
    return $marker
}

function Initialize-LsaInterop {
    # Windows Winlogon reads the protected DefaultPassword LSA secret, as used
    # by administrator-managed autologon. No password value is placed in HKLM.
    if (-not ('BycodaGuestLsa' -as [type])) {
        Add-Type -TypeDefinition @'
using System;
using System.Security;
using System.Runtime.InteropServices;
public static class BycodaGuestLsa {
  public const uint CreateSecretAccess = 0x20, ReadSecretAccess = 0x04;
  public const string SecretName = "DefaultPassword";
  [StructLayout(LayoutKind.Sequential)] struct Attributes { public int Length; public IntPtr RootDirectory, ObjectName; public uint Flags; public IntPtr SecurityDescriptor, SecurityQualityOfService; }
  [StructLayout(LayoutKind.Sequential)] struct Text { public ushort Length, MaximumLength; public IntPtr Buffer; }
  [DllImport("advapi32.dll")] static extern uint LsaOpenPolicy(IntPtr system, ref Attributes attrs, uint access, out IntPtr handle);
  [DllImport("advapi32.dll")] static extern uint LsaStorePrivateData(IntPtr handle, ref Text key, ref Text value);
  [DllImport("advapi32.dll")] static extern uint LsaClose(IntPtr handle);
  [DllImport("advapi32.dll")] static extern uint LsaRetrievePrivateData(IntPtr handle, ref Text key, out IntPtr data);
  [DllImport("advapi32.dll")] static extern uint LsaFreeMemory(IntPtr data);
  [DllImport("advapi32.dll")] static extern uint LsaNtStatusToWinError(uint status);
  static Text MakeKey() {
    var key = new Text();
    key.Buffer = Marshal.StringToHGlobalUni(SecretName);
    key.Length = checked((ushort)(SecretName.Length * 2));
    key.MaximumLength = checked((ushort)(key.Length + 2));
    return key;
  }
  public static void Store(SecureString value) {
    if (value == null || value.Length == 0 || value.Length > 32766) throw new ArgumentException("Invalid secret length");
    var attrs = new Attributes(); attrs.Length = Marshal.SizeOf(typeof(Attributes));
    IntPtr handle; uint status = LsaOpenPolicy(IntPtr.Zero, ref attrs, CreateSecretAccess, out handle);
    if (status != 0) throw new System.ComponentModel.Win32Exception((int)LsaNtStatusToWinError(status));
    var key = new Text(); var data = new Text();
    try {
      key = MakeKey();
      data.Buffer = Marshal.SecureStringToGlobalAllocUnicode(value); data.Length = checked((ushort)(value.Length * 2)); data.MaximumLength = checked((ushort)(data.Length + 2));
      status = LsaStorePrivateData(handle, ref key, ref data);
      if (status != 0) throw new System.ComponentModel.Win32Exception((int)LsaNtStatusToWinError(status));
    } finally {
      if (key.Buffer != IntPtr.Zero) Marshal.FreeHGlobal(key.Buffer);
      if (data.Buffer != IntPtr.Zero) Marshal.ZeroFreeGlobalAllocUnicode(data.Buffer);
      LsaClose(handle);
    }
  }
  public static bool Exists() {
    var attrs = new Attributes(); attrs.Length = Marshal.SizeOf(typeof(Attributes));
    IntPtr handle; uint status = LsaOpenPolicy(IntPtr.Zero, ref attrs, ReadSecretAccess, out handle);
    if (status != 0) throw new System.ComponentModel.Win32Exception((int)LsaNtStatusToWinError(status));
    var key = new Text(); IntPtr stored = IntPtr.Zero;
    try {
      key = MakeKey(); status = LsaRetrievePrivateData(handle, ref key, out stored);
      if (status == 0xC0000034) return false; // STATUS_OBJECT_NAME_NOT_FOUND
      if (status != 0) throw new System.ComponentModel.Win32Exception((int)LsaNtStatusToWinError(status));
      return stored != IntPtr.Zero && ((Text)Marshal.PtrToStructure(stored, typeof(Text))).Length > 0;
    } finally {
      if (stored != IntPtr.Zero) {
        var text = (Text)Marshal.PtrToStructure(stored, typeof(Text));
        for (int i = 0; i < text.Length; i++) Marshal.WriteByte(text.Buffer, i, 0);
        LsaFreeMemory(stored);
      }
      if (key.Buffer != IntPtr.Zero) Marshal.FreeHGlobal(key.Buffer);
      LsaClose(handle);
    }
  }
}
'@
    }
}

function Set-AutologonSecret([Security.SecureString]$Value) {
    Initialize-LsaInterop
    [BycodaGuestLsa]::Store($Value)
}

function Assert-WinlogonAvailable {
    $key = Get-Item -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon'
    $acl = Get-Acl -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon'
    $trusted = @('S-1-5-18', 'S-1-5-32-544', 'S-1-5-80-956008885-3418522649-1831038044-1853292631-2271478464')
    if ($acl.GetOwner([Security.Principal.SecurityIdentifier]).Value -notin $trusted) { throw 'Winlogon owner is not administrator/SYSTEM' }
    foreach ($ace in $acl.GetAccessRules($true, $true, [Security.Principal.SecurityIdentifier])) {
        if ($ace.PropagationFlags -band [Security.AccessControl.PropagationFlags]::InheritOnly) { continue }
        [long]$raw = $ace.RegistryRights
        if ($raw -lt 0) { $raw += 4294967296 }
        # Registry set/create/link/delete/WRITE_DAC/WRITE_OWNER or generic write/all.
        if ($ace.AccessControlType -eq 'Allow' -and ($raw -band 0x500d0026L) -and $ace.IdentityReference.Value -notin $trusted) { throw 'Winlogon key is writable by an untrusted identity' }
    }
    if ($key.GetValueNames() -contains 'DefaultPassword') { throw 'Existing plaintext Winlogon password is retained; administrator review is required' }
    if ($key.GetValue('AutoAdminLogon', '') -eq '1') { throw 'Existing autologon configuration is retained; inspect before changing guest session startup' }
}

function Assert-RegisteredRunner {
    $shell = 'C:\Program Files\PowerShell\7\pwsh.exe'
    foreach ($path in @($shell, $controlScript, 'C:\bycoda-actions\control\policy.json', 'C:\bycoda-actions\agent\.runner', 'C:\bycoda-actions\agent\.credentials', 'C:\bycoda-actions\agent\.credentials_rsaparams')) { Assert-AdminProtected $path }
    if ((Get-AuthenticodeSignature -LiteralPath $shell).Status -ne 'Valid') { throw 'Signed protected PowerShell 7 prerequisite is missing' }
    # Status deliberately supports the provisioning administrator. Its protected
    # production collector checks the actual VM, account, ACLs, hashes and network.
    $start = [Diagnostics.ProcessStartInfo]::new($shell)
    $start.UseShellExecute = $false; $start.CreateNoWindow = $true
    $start.EnvironmentVariables.Clear()
    $windows = [Environment]::GetFolderPath('Windows')
    $start.EnvironmentVariables['SystemRoot'] = $windows
    $start.EnvironmentVariables['WINDIR'] = $windows
    $start.EnvironmentVariables['PSModulePath'] = "C:\Program Files\PowerShell\7\Modules;$windows\System32\WindowsPowerShell\v1.0\Modules"
    $start.Arguments = '-NoLogo -NoProfile -NonInteractive -File C:\bycoda-actions\control\windows-runner.ps1 -Mode Status'
    $start.RedirectStandardOutput = $true; $start.RedirectStandardError = $true
    $process = [Diagnostics.Process]::Start($start)
    $stdout = $process.StandardOutput.ReadToEndAsync(); $stderr = $process.StandardError.ReadToEndAsync()
    $process.WaitForExit()
    $text = $stdout.GetAwaiter().GetResult(); $null = $stderr.GetAwaiter().GetResult()
    if ($process.ExitCode -ne 0) { throw 'Protected runner status check failed; session remains disabled' }
    $status = $text | ConvertFrom-Json
    if ($status.allowed -ne $true -or $status.protectedProvisioning -ne $true -or $status.runnerVersion -ne '2.338.2') { throw 'Protected runner status is not ready; session remains disabled' }
    $config = Get-Content -Raw -LiteralPath 'C:\bycoda-actions\agent\.runner' | ConvertFrom-Json
    if ($config.agentName -ne 'bycoda-windows-isolated-01' -or $config.gitHubUrl.TrimEnd('/') -ne 'https://github.com/bahadryalcn/bycoda' -or $config.workFolder -ne 'C:\bycoda-actions\work' -or $config.disableUpdate -ne $true) { throw 'Registered runner repository/work-root/pin does not match the production contract' }
    foreach ($unexpected in @('.runner_migrated', '.credentials_migrated')) { if (Test-Path -LiteralPath "C:\bycoda-actions\agent\$unexpected") { throw 'Review migrated runner configuration while stopped' } }
}

function Assert-SessionIdentity($Computer, [bool]$Elevated, [string]$IdentityName, [string]$Actual, [string]$Expected) {
    $isGuest = $Computer.Manufacturer -eq 'Microsoft Corporation' -and $Computer.Model -eq 'Virtual Machine' -and $Computer.HypervisorPresent
    if (-not $isGuest -or -not [Environment]::Is64BitProcess -or -not $Elevated -or $IdentityName -ine "$($Computer.Name)\BycodaAdmin" -or $Expected -notmatch '^[a-fA-F0-9]{8}(-[a-fA-F0-9]{4}){3}-[a-fA-F0-9]{12}$' -or $Expected -match '^(0|-)+$' -or $Expected -ine $Actual) { throw 'Session setup requires the exact new VM and its elevated local BycodaAdmin identity' }
}

$identity = [Security.Principal.WindowsIdentity]::GetCurrent()
$principal = [Security.Principal.WindowsPrincipal]::new($identity)
$admin = $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
$computer = Get-CimInstance Win32_ComputerSystem
$actualUuid = (Get-CimInstance Win32_ComputerSystemProduct).UUID
$guest = $computer.Manufacturer -eq 'Microsoft Corporation' -and $computer.Model -eq 'Virtual Machine' -and $computer.HypervisorPresent
$user = Get-LocalUser -Name $accountName -ErrorAction SilentlyContinue
$isMemberAdmin = $false
if ($user) { $isMemberAdmin = @((Get-LocalGroupMember -SID 'S-1-5-32-544') | Where-Object { $_.SID.Value -eq $user.SID.Value }).Count -gt 0 }
if ($Mode -in @('Plan', 'Status')) {
    [ordered]@{ mode = $Mode; actualVm = $guest; vmUuid = $actualUuid; administrator = $admin; accountExists = [bool]$user; accountAdministrator = $isMemberAdmin; runnerControlExists = (Test-Path -LiteralPath $controlScript); protectedRunnerPrepared = $null; sessionTaskExists = [bool](Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue); changed = $false } | ConvertTo-Json
    exit 0
}
Assert-SessionIdentity $computer $admin $identity.Name $actualUuid $ExpectedVmUuid
Assert-RegularPath $bootstrapRoot
if (-not (Test-Path -LiteralPath $bootstrapRoot)) {
    New-Item -ItemType Directory -Path $bootstrapRoot | Out-Null
    Set-AdminOnly $bootstrapRoot
} else { Assert-AdminProtected $bootstrapRoot }
if ($isMemberAdmin) { throw 'The runner identity must not be an administrator' }
if ($Mode -eq 'CreateAccount') {
    if ($user) { $marker = Assert-OwnedMarker; if ($marker.sid -ne $user.SID.Value -or -not $user.Enabled) { throw 'Runner SID changed or account is disabled' } }
    else {
        Assert-WinlogonAvailable
        if (Test-Path -LiteralPath $markerPath) { throw 'Existing ownership record without its account is retained' }
        if (Test-Path -LiteralPath "C:\Users\$accountName") { throw 'Existing unowned runner profile directory is retained' }
        Initialize-LsaInterop
        if ([BycodaGuestLsa]::Exists()) { throw 'Existing autologon LSA secret is retained; administrator review is required' }
        $bytes = New-Object byte[] 48
        $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
        try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
        $secure = $null
        try {
            $secure = [Security.SecureString]::new()
            $alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
            foreach ($byte in $bytes) { $secure.AppendChar($alphabet[$byte -band 63]) }
            foreach ($char in '!aA9'.ToCharArray()) { $secure.AppendChar($char) }
            $secure.MakeReadOnly()
            $user = New-LocalUser -Name $accountName -Password $secure -AccountNeverExpires -PasswordNeverExpires -UserMayNotChangePassword -Description 'Isolated bycoda CI runner'
            $usersMember = @(Get-LocalGroupMember -SID 'S-1-5-32-545' | Where-Object { $_.SID.Value -eq $user.SID.Value }).Count -gt 0
            if (-not $usersMember) { Add-LocalGroupMember -SID 'S-1-5-32-545' -Member $user }
            Set-AutologonSecret $secure
            [ordered]@{ kind = 'bycoda-runner-session-v1'; vmUuid = $actualUuid; account = $accountName; sid = $user.SID.Value } | ConvertTo-Json | Set-Content -LiteralPath $markerPath -Encoding utf8
            Set-AdminOnly $markerPath
        } finally { if ($secure) { $secure.Dispose() }; [Array]::Clear($bytes, 0, $bytes.Length) }
    }
    $profile = Get-CimInstance Win32_UserProfile | Where-Object SID -eq $user.SID.Value
    if (-not $profile) {
        if (-not ('BycodaGuestProfile' -as [type])) {
            Add-Type -TypeDefinition @'
using System; using System.Text; using System.Runtime.InteropServices;
public static class BycodaGuestProfile {
 [DllImport("userenv.dll", CharSet=CharSet.Unicode, ExactSpelling=true)] public static extern int CreateProfile(string sid, string user, StringBuilder path, uint count);
}
'@
        }
        Assert-RegularPath "C:\Users\$accountName"
        $profilePath = [Text.StringBuilder]::new(260)
        $result = [BycodaGuestProfile]::CreateProfile($user.SID.Value, $accountName, $profilePath, 260)
        if ($result -ne 0 -or $profilePath.ToString() -ne "C:\Users\$accountName") { throw ('Windows did not create the expected real runner profile; HRESULT={0}, path={1}' -f $result, $profilePath.ToString()) }
    } elseif ($profile.LocalPath -ne "C:\Users\$accountName" -or $profile.Special) { throw 'Unexpected existing runner profile' }
    Assert-RegularPath "C:\Users\$accountName"
    Initialize-LsaInterop
    if (-not [BycodaGuestLsa]::Exists()) { throw 'Owned account has no stored autologon secret; no password is reset automatically' }
    $autoEnabled = (Get-Item -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon').GetValue('AutoAdminLogon', '') -eq '1'
    [ordered]@{ mode = $Mode; account = $accountName; sid = $user.SID.Value; profile = "C:\Users\$accountName"; administrator = $false; passwordReturned = $false; autoLogonEnabled = $autoEnabled } | ConvertTo-Json
    exit 0
}
$marker = Assert-OwnedMarker
if (-not $user -or $marker.sid -ne $user.SID.Value -or -not $user.Enabled) { throw 'Missing enabled owned runner identity' }
$existing = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
if ($existing) { throw 'Existing session task retained; inspect it before changing startup behavior' }
Assert-WinlogonAvailable
Assert-RegisteredRunner
Initialize-LsaInterop
if (-not [BycodaGuestLsa]::Exists()) { throw 'Stored autologon secret is missing; session remains disabled' }
$action = New-ScheduledTaskAction -Execute 'C:\Program Files\PowerShell\7\pwsh.exe' -Argument '-NoProfile -NonInteractive -WindowStyle Hidden -File C:\bycoda-actions\control\windows-runner.ps1 -Mode Run'
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user.SID.Value
$taskPrincipal = New-ScheduledTaskPrincipal -UserId $user.SID.Value -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit ([TimeSpan]::Zero)
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $taskPrincipal -Settings $settings -Description 'One protected bycoda runner in the isolated guest desktop' | Out-Null
$logon = 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon'
New-ItemProperty -Path $logon -Name DefaultUserName -Value $accountName -PropertyType String -Force | Out-Null
New-ItemProperty -Path $logon -Name DefaultDomainName -Value $env:COMPUTERNAME -PropertyType String -Force | Out-Null
New-ItemProperty -Path $logon -Name AutoAdminLogon -Value '1' -PropertyType String -Force | Out-Null
if ((Get-Item -LiteralPath $logon).GetValueNames() -contains 'DefaultPassword') { throw 'Unexpected plaintext autologon password detected; session acceptance failed' }
[ordered]@{ mode = $Mode; task = $taskName; account = $accountName; lsaAutologon = $true; plaintextPasswordRegistry = $false; scheduled = $true; runnerStarted = $false; guestRestartRequired = $true } | ConvertTo-Json
