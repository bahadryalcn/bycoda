import { generateKeyPairSync, sign } from "node:crypto";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { expect, it } from "vitest";
import { applyNativeAdmission, nativeAdmissionRegistryPath, previewNativeAdmission } from "./native-admission-cli";
import { loadNativeAdmissionRegistry, NativeAdmissionOwner, nativeAdmissionBytes, nativeAdmissionDigest } from "./assistant/native/assistant-native-admission";

it("requires the exact reviewed proposal and current revision for local enrollment and revocation", async () => {
  const directory = await mkdtemp(join(tmpdir(), "native-registry-"));
  const keyPath = join(directory, "reviewed.pem");
  const key = generateKeyPairSync("ed25519");
  await writeFile(keyPath, key.publicKey.export({ format: "pem", type: "spki" }));
  const change = { action: "enroll" as const, hostId: "host", installationId: "desktop", publicKeyPath: keyPath };
  const proposal = await previewNativeAdmission(directory, change);
  await expect(applyNativeAdmission(directory, change, "0".repeat(64), proposal.revision)).rejects.toThrow("preview again");
  await expect(readFile(nativeAdmissionRegistryPath(directory))).rejects.toThrow();
  await applyNativeAdmission(directory, change, proposal.proposalHash, proposal.revision);
  expect(await loadNativeAdmissionRegistry(nativeAdmissionRegistryPath(directory), "host")).toHaveLength(1);
  await expect(applyNativeAdmission(directory, change, proposal.proposalHash, proposal.revision)).rejects.toThrow();
  const revoke = { action: "revoke" as const, hostId: "host", installationId: "desktop" };
  const removal = await previewNativeAdmission(directory, revoke);
  await expect(applyNativeAdmission(directory, revoke, removal.proposalHash, proposal.revision)).rejects.toThrow("preview again");
  await applyNativeAdmission(directory, revoke, removal.proposalHash, removal.revision);
  expect(await loadNativeAdmissionRegistry(nativeAdmissionRegistryPath(directory), "host")).toEqual([]);
  await writeFile(nativeAdmissionRegistryPath(directory), "not json");
  await expect(previewNativeAdmission(directory, change)).rejects.toThrow();
});

it("serializes revocation behind actual effect settlement and rejects stale authority", async () => {
  const directory = await mkdtemp(join(tmpdir(), "native-effect-"));
  const keyPath = join(directory, "key.pem");
  const key = generateKeyPairSync("ed25519");
  await writeFile(keyPath, key.publicKey.export({ format: "pem", type: "spki" }));
  const enroll = { action: "enroll" as const, hostId: "host", installationId: "desktop", publicKeyPath: keyPath };
  const proposal = await previewNativeAdmission(directory, enroll);
  await applyNativeAdmission(directory, enroll, proposal.proposalHash, proposal.revision);
  const owner = new NativeAdmissionOwner(nativeAdmissionRegistryPath(directory), "host");
  const request = { installationId: "desktop", hostId: "host", action: "assistant.call", requestDigest: nativeAdmissionDigest("{}") };
  const challenge = await owner.challenge(request);
  const revision = await owner.consume(request, { challenge, signature: sign(null, nativeAdmissionBytes(challenge), key.privateKey).toString("base64url") });
  const revoke = { action: "revoke" as const, hostId: "host", installationId: "desktop" };
  const removal = await previewNativeAdmission(directory, revoke);
  let effectStarted!: () => void;
  let finishEffect!: () => void;
  const started = new Promise<void>(resolve => { effectStarted = resolve; });
  const settled = new Promise<void>(resolve => { finishEffect = resolve; });
  let validAfter = () => false;
  const effect = owner.withEffect("desktop", revision, async lease => { validAfter = lease.valid; effectStarted(); await settled; expect(lease.valid()).toBe(true); });
  await started;
  let revoked = false;
  const removalRun = applyNativeAdmission(directory, revoke, removal.proposalHash, removal.revision).then(() => { revoked = true; });
  await new Promise(resolve => setTimeout(resolve, 75));
  expect(revoked).toBe(false);
  expect(validAfter()).toBe(true);
  finishEffect();
  await effect;
  expect(validAfter()).toBe(false);
  await removalRun;
  expect(revoked).toBe(true);
  await expect(owner.withEffect("desktop", revision, async () => undefined)).rejects.toThrow("revoked");
});
